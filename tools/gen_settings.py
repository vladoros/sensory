import os
from typing import NamedTuple
from xml.sax.saxutils import escape

ROOT = os.path.join(os.path.dirname(__file__), '..', 'resources')


class Setting(NamedTuple):
    id: str
    kind: str
    default: object
    title: str
    options: list | None


