    Setting('Language', 'list', 0, 'Language', [(0, 'Same as watch'), (1, 'English'), (2, 'Русский'), (3, 'Deutsch'), (4, 'Polski'), (5, 'Español'), (6, 'Беларуская')]),
    Setting('TimeFormat', 'list', 0, 'Time format', [(0, 'Same as watch'), (1, '24-hour'), (2, '12-hour')]),
    Setting('TileTheme', 'list', 0, 'Tiles', [(0, 'Light'), (1, 'Dark')]),
    Setting('Typeface', 'list', 0, 'Font', [(0, 'Roboto'), (1, 'Inter')]),
    Setting('FieldBottom', 'list', 0, 'Next to the date', [(0, 'Steps'), (1, 'Distance'), (2, 'Active calories'), (3, 'Heart rate'), (4, 'Nothing')]),
    Setting('DateFormat', 'list', 0, 'Date format', [(0, 'By language (Oct 28)'), (1, '28.10.2026'), (2, '28/10/2026'), (3, '10/28/2026'), (4, '2026-10-28')]),
    Setting('WeatherEnabled', 'boolean', True, 'Show weather', None),
    Setting('FieldWeather', 'list', 0, 'Under the temperature', [(0, "Today's high and low"), (1, 'Sunrise and sunset'), (2, 'Chance of precipitation'), (3, 'Wind')]),
